/**
 * The per-run session marker: proof of *which run* the agent answered.
 *
 * The controller puts its run id in the job. After the agent verifies the job
 * and before it executes anything, it writes a marker into the job's result
 * directory naming that run and carrying 32 random bytes. The controller reads
 * the marker back and records the evidence in the manifest.
 *
 * A quit or close path checks the marker before it acts. A marker that names
 * another run — or no marker at all — means the destination is unproven: the
 * path does nothing and reports `A8N-AE-002`. The secret is generated by the
 * agent, never derived from the job id, a timestamp or anything else guessable,
 * so a marker cannot be predicted or replayed from public facts.
 *
 * This is the isolated-backend half of the driver's own session marker (#43).
 * It proves the job reached this run's agent; the driver's marker proves which
 * After Effects instance a script reached when the run talks to AE directly.
 */

import type { FileChannel } from "./channel.js";
import {
  isJobId,
  type AgentIdentity,
  type DecodeOutcome,
} from "./job.js";
import { isRunId } from "./lock.js";

export const SESSION_MARKER_SCHEMA_VERSION = "1.0";
export const SESSION_SECRET_BYTES = 32;

const SECRET_PATTERN = /^[0-9a-f]{64}$/;

export type SessionMarker = {
  readonly schemaVersion: typeof SESSION_MARKER_SCHEMA_VERSION;
  /** The controller's run id, copied from the job; never derived here. */
  readonly runId: string;
  readonly jobId: string;
  /** 64 hex characters from `SESSION_SECRET_BYTES` random bytes. */
  readonly secret: string;
  readonly agent: AgentIdentity;
  readonly createdAt: string;
};

/** `results/<jobId>/session-marker.json`; a job id is one path component. */
export function sessionMarkerPath(jobId: string): string {
  if (!isJobId(jobId)) {
    throw new Error(`job id "${jobId}" cannot be used as a path component`);
  }
  return `results/${jobId}/session-marker.json`;
}

export type CreateSessionMarkerInput = {
  readonly runId: string;
  readonly jobId: string;
  readonly agent: AgentIdentity;
  readonly now: () => Date;
  readonly random: (size: number) => Uint8Array;
};

/** The agent's side: mint a marker for the job it just verified. */
export function createSessionMarker(input: CreateSessionMarkerInput): SessionMarker {
  if (!isRunId(input.runId)) {
    throw new Error(`run id "${input.runId}" cannot be used as a path component`);
  }
  sessionMarkerPath(input.jobId);
  const bytes = input.random(SESSION_SECRET_BYTES);
  if (bytes.length < SESSION_SECRET_BYTES) {
    throw new Error(
      `the random source returned ${bytes.length} bytes; ${SESSION_SECRET_BYTES} are required`,
    );
  }
  return {
    schemaVersion: SESSION_MARKER_SCHEMA_VERSION,
    runId: input.runId,
    jobId: input.jobId,
    secret: Buffer.from(bytes.subarray(0, SESSION_SECRET_BYTES)).toString("hex"),
    agent: input.agent,
    createdAt: input.now().toISOString(),
  };
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function stringField(record: Record<string, unknown>, key: string): string | null {
  const value = record[key];
  return typeof value === "string" && value !== "" ? value : null;
}

function decodeAgent(value: unknown): AgentIdentity | null {
  if (!isRecord(value)) {
    return null;
  }
  const id = stringField(value, "id");
  const host = stringField(value, "host");
  const user = stringField(value, "user");
  const version = stringField(value, "version");
  const sessionId = value["sessionId"];
  if (id === null || host === null || user === null || version === null) {
    return null;
  }
  if (typeof sessionId !== "number" || !Number.isInteger(sessionId) || sessionId < 0) {
    return null;
  }
  return { id, host, user, sessionId, version };
}

/** A marker is data: every field is checked before it is trusted. */
export function decodeSessionMarker(bytes: Uint8Array): DecodeOutcome<SessionMarker> {
  let parsed: unknown;
  try {
    parsed = JSON.parse(Buffer.from(bytes).toString("utf-8"));
  } catch {
    return { ok: false, detail: "session-marker.json is not valid JSON" };
  }
  if (!isRecord(parsed)) {
    return { ok: false, detail: "session-marker.json is not an object" };
  }
  if (parsed["schemaVersion"] !== SESSION_MARKER_SCHEMA_VERSION) {
    return {
      ok: false,
      detail: `unsupported session marker schema ${String(parsed["schemaVersion"])}`,
    };
  }
  const runId = stringField(parsed, "runId");
  const jobId = stringField(parsed, "jobId");
  const secret = stringField(parsed, "secret");
  const createdAt = stringField(parsed, "createdAt");
  const agent = decodeAgent(parsed["agent"]);
  if (runId === null || jobId === null || secret === null || createdAt === null || agent === null) {
    return { ok: false, detail: "session-marker.json is missing a required field" };
  }
  if (!isRunId(runId)) {
    return { ok: false, detail: `marker runId "${runId}" is not in the expected form` };
  }
  if (!isJobId(jobId)) {
    return { ok: false, detail: `marker jobId "${jobId}" is not in the expected form` };
  }
  if (!SECRET_PATTERN.test(secret)) {
    return { ok: false, detail: "marker secret is not 64 hex characters" };
  }
  if (Number.isNaN(Date.parse(createdAt))) {
    return { ok: false, detail: "marker createdAt is not an ISO-8601 timestamp" };
  }
  return {
    ok: true,
    value: {
      schemaVersion: SESSION_MARKER_SCHEMA_VERSION,
      runId,
      jobId,
      secret,
      agent,
      createdAt,
    },
  };
}

export function encodeSessionMarker(marker: SessionMarker): Uint8Array {
  return Buffer.from(`${JSON.stringify(marker, null, 2)}\n`, "utf-8");
}

export async function writeSessionMarker(
  channel: FileChannel,
  marker: SessionMarker,
): Promise<void> {
  await channel.writeAtomic(sessionMarkerPath(marker.jobId), encodeSessionMarker(marker));
}

export type MarkerRead =
  | { readonly state: "missing" }
  | { readonly state: "unreadable"; readonly detail: string }
  | { readonly state: "ok"; readonly marker: SessionMarker };

export async function readSessionMarker(
  channel: FileChannel,
  jobId: string,
): Promise<MarkerRead> {
  let bytes: Uint8Array | null;
  try {
    bytes = await channel.read(sessionMarkerPath(jobId));
  } catch (error) {
    return {
      state: "unreadable",
      detail: error instanceof Error ? error.message : String(error),
    };
  }
  if (bytes === null) {
    return { state: "missing" };
  }
  const decoded = decodeSessionMarker(bytes);
  return decoded.ok
    ? { state: "ok", marker: decoded.value }
    : { state: "unreadable", detail: decoded.detail };
}

/** What a quit or close path may conclude about the run's destination. */
export type DestinationVerdict =
  | { readonly proven: true; readonly proof: "marker"; readonly marker: SessionMarker }
  | { readonly proven: false; readonly code: "A8N-AE-002"; readonly detail: string };

export type ExpectedDestination = {
  readonly runId: string;
  readonly jobId: string;
  /** The agent this controller is configured to talk to. */
  readonly agent: AgentIdentity;
};

function sameAccount(left: string, right: string): boolean {
  // Windows account and host names are case-insensitive.
  return left.toLowerCase() === right.toLowerCase();
}

/** The marker must name this run, this job and this agent; anything else acts on nothing. */
export function verifySessionMarker(
  marker: SessionMarker,
  expected: ExpectedDestination,
): DestinationVerdict {
  if (marker.runId !== expected.runId) {
    return {
      proven: false,
      code: "A8N-AE-002",
      detail: `the marker names run "${marker.runId}", not this run "${expected.runId}"`,
    };
  }
  if (marker.jobId !== expected.jobId) {
    return {
      proven: false,
      code: "A8N-AE-002",
      detail: `the marker names job "${marker.jobId}", not this run's job "${expected.jobId}"`,
    };
  }
  if (marker.agent.id !== expected.agent.id) {
    return {
      proven: false,
      code: "A8N-AE-002",
      detail: `the marker was written by agent "${marker.agent.id}", not "${expected.agent.id}"`,
    };
  }
  if (
    !sameAccount(marker.agent.host, expected.agent.host) ||
    !sameAccount(marker.agent.user, expected.agent.user) ||
    marker.agent.sessionId !== expected.agent.sessionId
  ) {
    return {
      proven: false,
      code: "A8N-AE-002",
      detail:
        `the marker was written by ${marker.agent.host}\\${marker.agent.user} in session ` +
        `${marker.agent.sessionId}, not ${expected.agent.host}\\${expected.agent.user} in ` +
        `session ${expected.agent.sessionId}`,
    };
  }
  return { proven: true, proof: "marker", marker };
}

/** Read and verify in one step; a missing or unreadable marker is unproven, never assumed. */
export async function proveRunDestination(
  channel: FileChannel,
  expected: ExpectedDestination,
): Promise<DestinationVerdict> {
  const read = await readSessionMarker(channel, expected.jobId);
  if (read.state === "missing") {
    return {
      proven: false,
      code: "A8N-AE-002",
      detail: `the agent wrote no session marker for job "${expected.jobId}"`,
    };
  }
  if (read.state === "unreadable") {
    return {
      proven: false,
      code: "A8N-AE-002",
      detail: `the session marker for job "${expected.jobId}" is unreadable: ${read.detail}`,
    };
  }
  return verifySessionMarker(read.marker, expected);
}
