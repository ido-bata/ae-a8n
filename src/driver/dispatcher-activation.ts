/**
 * The marker that identifies a dispatcher `activate.jsx` this package
 * generated, the whole-line check both the transport's Startup-file
 * ownership test and the owned `-r` activation delivery apply, and the
 * canonical generator/parser pair the `-r` delivery binds its bytes to.
 *
 * This lives in its own leaf module — not in `dispatcher-transport.ts` —
 * because `script-invocation.ts` needs the check and importing the
 * transport would close an import cycle
 * (`script-invocation` → `dispatcher-transport` → `driver` →
 * `script-invocation`). It imports only `bootstrap.js`, which has no
 * project-internal dependencies, so the leaf stays acyclic.
 */

import { join } from "node:path";

import { es3StringLiteral, toPosixPath } from "./bootstrap.js";

/** First line of every generated activate.jsx; also the Startup ownership marker. */
export const ACTIVATION_MARKER =
  "// ae-a8n in-AE dispatcher activation. Generated by @ido-bata/ae-a8n; do not edit.";

/**
 * Whether `content` is recognisably a script this package generated: the
 * marker must appear as a whole line, so a foreign file that merely quotes
 * the string inline is not treated as ours.
 *
 * This is the *ownership heuristic* used for the Scripts/Startup install
 * and uninstall paths, where an older generated file must still be
 * recognised. It is NOT sufficient for `-r` delivery — see
 * {@link isCanonicalDispatcherActivationScript}.
 */
export function isDispatcherActivationScript(content: string): boolean {
  return content.split(/\r?\n/).includes(ACTIVATION_MARKER);
}

/**
 * Per-delivery proof nonce format: 16 random bytes as lowercase hex. The
 * nonce is unique per `activateDispatcher()` call and is the only evidence
 * that *this* delivery — not a dispatcher that was already answering the
 * channel — activated the After Effects the script ran in.
 */
export const ACTIVATION_NONCE_RE = /^[a-f0-9]{32}$/;

export type DispatcherActivationConfig = {
  /** Channel directory, exactly as `DispatcherTransport` resolved it. */
  readonly channelDir: string;
  /** The channel token from `channel.json`. */
  readonly token: string;
  /**
   * Optional per-delivery nonce. Present only on the private per-call
   * delivery file `prepareActivationScript()` stages; the human-facing
   * `activate.jsx` carries none.
   */
  readonly nonce?: string;
};

/**
 * The exact bytes of a generated activation script. Deterministic in
 * `(channelDir, token, nonce)`: the same inputs always produce the same
 * file, which is what lets {@link isCanonicalDispatcherActivationScript}
 * prove a delivered file is byte-identical to package output rather than
 * merely marker-bearing.
 */
export function dispatcherActivationScript(config: DispatcherActivationConfig): string {
  const lines = [
    ACTIVATION_MARKER,
    "// Run once per After Effects process: File > Scripts > Run Script File,",
    "// or install into the per-user Scripts/Startup folder (see docs).",
    "var __a8n = {",
    "  dispatcher: {",
    `    root: ${es3StringLiteral(toPosixPath(config.channelDir))},`,
  ];
  if (config.nonce === undefined) {
    lines.push(`    token: ${es3StringLiteral(config.token)}`);
  } else {
    lines.push(
      `    token: ${es3StringLiteral(config.token)},`,
      `    nonce: ${es3StringLiteral(config.nonce)}`,
    );
  }
  lines.push(
    "  }",
    "};",
    `$.evalFile(new File(${es3StringLiteral(toPosixPath(join(config.channelDir, "a8n-host.js")))}));`,
    "",
  );
  return lines.join("\n");
}

export type ParsedDispatcherActivation = {
  readonly channelDir: string;
  readonly token: string;
  readonly nonce: string | null;
};

/** One `    <name>: <json-string-literal>` line, captured for JSON.parse. */
function activationField(content: string, name: string): string | null {
  const match = new RegExp(`^    ${name}: ("(?:[^"\\\\]|\\\\.)*")`, "m").exec(content);
  return match === null ? null : match[1] ?? null;
}

/**
 * Extracts the `(channelDir, token, nonce)` a generated script embeds.
 * This is deliberately only a *candidate* extraction: the strict check is
 * {@link isCanonicalDispatcherActivationScript}, which regenerates the
 * bytes and compares them whole, so anything this parser misses or
 * misreads simply fails closed.
 */
export function parseDispatcherActivationScript(
  content: string,
): ParsedDispatcherActivation | null {
  const rootLiteral = activationField(content, "root");
  const tokenLiteral = activationField(content, "token");
  if (rootLiteral === null || tokenLiteral === null) {
    return null;
  }
  const nonceLiteral = activationField(content, "nonce");
  try {
    const channelDir = JSON.parse(rootLiteral) as unknown;
    const token = JSON.parse(tokenLiteral) as unknown;
    const nonce = nonceLiteral === null ? null : (JSON.parse(nonceLiteral) as unknown);
    if (
      typeof channelDir !== "string" ||
      typeof token !== "string" ||
      (nonce !== null && typeof nonce !== "string")
    ) {
      return null;
    }
    return { channelDir, token, nonce };
  } catch {
    return null;
  }
}

/**
 * Whether `content` is byte-identical to what this package's generator
 * produces for the parameters it embeds — the check the owned `-r`
 * delivery applies before spawning.
 *
 * A file that merely contains the marker line, appends arbitrary JSX, or
 * differs from the canonical bytes in any way fails: delivery is bound to
 * exact generated output, not to a recognisable shape. Note what this does
 * and does not prove: it proves the *bytes* are package-generated, not
 * that the file at `scriptPath` cannot be swapped before AE reads it —
 * `deliverActivationScript` closes that gap by delivering a private copy
 * of the verified bytes, and the remaining same-user race is documented
 * there.
 */
export function isCanonicalDispatcherActivationScript(content: string): boolean {
  const parsed = parseDispatcherActivationScript(content);
  if (parsed === null) {
    return false;
  }
  return (
    dispatcherActivationScript({
      channelDir: parsed.channelDir,
      token: parsed.token,
      ...(parsed.nonce === null ? {} : { nonce: parsed.nonce }),
    }) === content
  );
}
